"""Hash public PyPI wheels for the tested Linux amd64 / CPython 3.14 runtime.

Run with the documented development Python: python tools/generate_runtime_lock.py.
This does not upgrade requirements.runtime.in or execute downloaded packages.
"""

import ast
import hashlib
import importlib.metadata
import json
import re
import subprocess
import sys
import tempfile
import urllib.request
import zipfile
from email.parser import BytesParser
from pathlib import Path


BACKEND = Path(__file__).resolve().parents[1]


def canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def check_source_imports(pins: dict[str, str]) -> None:
    """Catch a missing direct dependency, even when other pins still resolve."""
    modules = set()
    for path in [BACKEND / "run.py", *(BACKEND / "app").rglob("*.py")]:
        for node in ast.walk(ast.parse(path.read_text(encoding="utf-8-sig"))):
            if isinstance(node, ast.Import):
                modules.update(alias.name.split(".")[0] for alias in node.names)
            elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
                modules.add(node.module.split(".")[0])
    distributions = importlib.metadata.packages_distributions()
    for module in sorted(modules - sys.stdlib_module_names - {"app"}):
        packages = {canonical(name) for name in distributions.get(module, [])}
        if not packages.intersection(pins):
            raise ValueError(f"Runtime pins do not cover imported module: {module}")


def main() -> None:
    pins = {}
    for line in (BACKEND / "requirements.runtime.in").read_text().splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        match = re.fullmatch(r"([A-Za-z0-9_.-]+)==([A-Za-z0-9_.+-]+)", line.strip())
        if not match:
            raise ValueError("Runtime input must contain exact version pins only")
        name, version = match.groups()
        if canonical(name) in pins:
            raise ValueError("Duplicate runtime package")
        pins[canonical(name)] = version
    check_source_imports(pins)

    with tempfile.TemporaryDirectory(prefix="smartnavigator-runtime-lock-") as directory:
        subprocess.run(
            [sys.executable, "-m", "pip", "--isolated", "download",
             "--index-url", "https://pypi.org/simple", "--no-deps",
             "--only-binary=:all:", "--platform", "manylinux_2_28_x86_64",
             "--platform", "manylinux2014_x86_64", "--python-version", "3.14",
             "--implementation", "cp", "--abi", "cp314",
             "--dest", directory, "-r", str(BACKEND / "requirements.runtime.in")],
            check=True,
        )
        hashes = {}
        for wheel in sorted(Path(directory).glob("*.whl")):
            with zipfile.ZipFile(wheel) as archive:
                metadata_path = next(
                    name for name in archive.namelist() if name.endswith(".dist-info/METADATA")
                )
                metadata = BytesParser().parsebytes(archive.read(metadata_path))
            name, version = canonical(metadata["Name"]), metadata["Version"]
            if pins.get(name) != version or name in hashes:
                raise ValueError("Downloaded wheels do not match the runtime input")
            with wheel.open("rb") as stream:
                digest = hashlib.file_digest(stream, "sha256").hexdigest()
            # Check the downloaded content against the publisher's public metadata.
            with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as response:
                published = json.load(response)
            expected = next(
                item["digests"]["sha256"] for item in published["urls"]
                if item["filename"] == wheel.name
            )
            if digest != expected:
                raise ValueError("Downloaded wheel digest differs from public PyPI metadata")
            hashes[name] = digest
        if set(hashes) != set(pins):
            raise ValueError("Some pinned runtime packages have no matching Linux wheel")

    header = (
        "# Generated by tools/generate_runtime_lock.py from requirements.runtime.in.\n"
        "# Target: Linux amd64, CPython 3.14 (GIL build), binary wheels only.\n"
        "# Install with --require-hashes --only-binary=:all:.\n"
        "# Test all changes before committing a regenerated lock.\n"
    )
    lines = [f"{name}=={pins[name]} --hash=sha256:{hashes[name]}" for name in sorted(pins)]
    (BACKEND / "requirements.runtime.lock").write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(lines)} verified runtime wheel pins")


if __name__ == "__main__":
    main()
